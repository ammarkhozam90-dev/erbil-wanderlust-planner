export const NATIONALITY_NAMES = NATIONALITIES.map((option) => option.name);

export function searchNationalities(query: string, limit = 8) {
  const normalized = query.trim().toLocaleLowerCase();
  if (!normalized) return NATIONALITIES.slice(0, limit);
  return NATIONALITIES
    .filter((option) => option.name.toLocaleLowerCase().includes(normalized))
    .slice(0, limit);
}
